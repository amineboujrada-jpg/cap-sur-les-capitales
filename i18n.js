let currentLang = "fr";

function detectLang() {
  const wanted = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "en"]);
  for (const tag of wanted) {
    const base = String(tag).toLowerCase().split("-")[0];
    if (SUPPORTED_LANGS.includes(base)) return base;
  }
  return "en"; // langue absente : on passe à l'anglais
}

function t(key, vars) {
  let text = (STRINGS[currentLang] && STRINGS[currentLang][key]) ?? STRINGS.en[key] ?? key;
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.split(`{${name}}`).join(String(value));
  return text;
}
